#!/usr/bin/env python3
"""Merge aigov-nemo-common (actions.py, rails.co, prompts.yml) into every per-config ConfigMap.

Each guardrail config gets one self-contained ConfigMap, rendered from the single-source files
11-nemo-common.yaml + 12-nemo-configs.yaml, so shared actions and prompts are maintained in one place.

Usage: python3 -I scripts/render-nemo-configs.py  -> writes .state/12-nemo-configs.rendered.yaml (then rendered with envsubst by setup.sh)
"""
import pathlib
import sys

import yaml

import os

# Substitute only the demo template variables (same explicit list as scripts/lib.sh RENDER_VARS) before parsing;
# Colang variables such as $user_message must stay untouched.
VARS = ["DEMO_NS", "MODEL_NS", "MAAS_NS", "MONITORING_NS", "PART_OF", "BRAND", "MAAS_URL", "CLUSTER_DOMAIN",
        "LLM_TEMPLATE", "MODEL_URI", "MODEL_SERVED_NAME", "MODEL_ID", "SMALL_MODEL_ID"]


def subst(text):
    for v in VARS:
        if "${%s}" % v in text:
            if v not in os.environ:
                sys.exit(f"render-nemo-configs: ${{{v}}} used but not set (run via scripts/setup.sh)")
            text = text.replace("${%s}" % v, os.environ[v])
    return text


root = pathlib.Path(__file__).resolve().parent.parent / "manifests"
common = yaml.safe_load(subst((root / "11-nemo-common.yaml").read_text()))
configs = yaml.safe_load(subst((root / "12-nemo-configs.yaml").read_text()))

out = []
for cm in configs["items"]:
    merged = dict(common["data"])
    clash = set(merged) & set(cm["data"])
    if clash:
        sys.exit(f"{cm['metadata']['name']}: keys clash with common: {clash}")
    merged.update(cm["data"])
    cm = dict(cm)
    cm["data"] = merged
    cm["metadata"].setdefault("annotations", {})["aigov/rendered-from"] = "11-nemo-common.yaml+12-nemo-configs.yaml"
    out.append(cm)


class _Literal(str):
    pass


def _lit(dumper, data):
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|" if "\n" in data else None)


yaml.add_representer(str, _lit)
doc = {"apiVersion": "v1", "kind": "List", "items": out}
state = root.parent / ".state"
state.mkdir(exist_ok=True)
target = state / "12-nemo-configs.rendered.yaml"
target.write_text("# GENERATED by scripts/render-nemo-configs.py, do not edit; edit 11-nemo-common.yaml / 12-nemo-configs.yaml\n"
                  + yaml.dump(doc, sort_keys=False, width=200))
print(f"wrote {target} with {len(out)} ConfigMaps")
